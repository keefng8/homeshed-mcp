def splice(readme: str, new: str) -> str:
    i, j = readme.find(START), readme.find(END)
    if i < 0 or j < i:
        raise SystemExit(f"README is missing the {START} ... {END} markers")
    return readme[:i] + new + readme[j + len(END):]


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--package", required=True, help="PyPI package and command name")
    p.add_argument("--readme", type=Path, default=Path("README.md"))
    p.add_argument("--check", action="store_true", help="exit 1 if the README is stale")
    a = p.parse_args(argv)
    old = a.readme.read_text(encoding="utf-8")
    new = splice(old, block(a.package))
    if a.check:
        if new != old:
            print("README install section is stale: run python scripts/gen_install.py", file=sys.stderr)
            return 1
        return 0
    a.readme.write_text(new, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
