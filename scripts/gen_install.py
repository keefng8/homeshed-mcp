"""Generate the README's install section: one-click buttons, one-line commands and per-client configs.

Every link and snippet is built from one package name, so a rename is a single re-run:
    python scripts/gen_install.py --package my-server
    python scripts/gen_install.py --package my-server --check   # CI: exit 1 if README.md is stale
"""
import argparse
import base64
import json
import sys
from pathlib import Path
from urllib.parse import quote, urlencode

START = "<!-- INSTALL:START"
END = "<!-- INSTALL:END -->"


def compact(obj) -> str:
    return json.dumps(obj, separators=(",", ":"))


def links(pkg: str) -> dict[str, str]:
    stdio = {"command": "uvx", "args": [pkg]}
    cursor_cfg = base64.b64encode(compact(stdio).encode()).decode()
    vscode_cfg = compact({"type": "stdio", **stdio})
    vscode = "https://insiders.vscode.dev/redirect/mcp/install?" + urlencode({"name": pkg, "config": vscode_cfg}, quote_via=quote)
    return {
        "cursor": "https://cursor.com/en/install-mcp?" + urlencode({"name": pkg, "config": cursor_cfg}, quote_via=quote),
        "vscode": vscode,
        "vscode_insiders": vscode + "&quality=insiders",
    }


def block(pkg: str, fence: str = "```") -> str:
    l = links(pkg)
